"""TransferQueue-backed replay metadata used by the Search-R1 V1 trainers."""

from __future__ import annotations

import time
from dataclasses import dataclass
from typing import Any, Protocol


@dataclass(frozen=True)
class KVBatchMeta:
    """Serializable subset of TransferQueue's KVBatchMeta contract."""

    partition_id: str
    keys: list[str]
    tags: list[dict[str, Any]]


class ReplayStore(Protocol):
    def kv_list(self): ...

    def kv_clear(self, *, partition_id: str, keys: list[str]): ...


class TransferQueueReplayStore:
    """Late-import adapter so metadata tests do not initialize TransferQueue."""

    def kv_list(self):
        import transfer_queue as tq

        return tq.kv_list()

    def kv_clear(self, *, partition_id: str, keys: list[str]):
        import transfer_queue as tq

        return tq.kv_clear(partition_id=partition_id, keys=keys)


class ReplayBuffer:
    """Synchronous group sampler matching the upstream V1 queue tag model."""

    TERMINAL = frozenset({"finished", "failure"})

    def __init__(self, store: ReplayStore | None = None, *, poll_interval: float = 0.1, timeout: float | None = None):
        if poll_interval < 0:
            raise ValueError("poll_interval must be non-negative")
        self.store = store or TransferQueueReplayStore()
        self.poll_interval = poll_interval
        self.timeout = timeout

    def _snapshot(self, partition_id: str) -> tuple[dict[str, dict], dict[str, dict]]:
        all_partitions = self.store.kv_list() or {}
        items = all_partitions.get(partition_id, {})
        prompts: dict[str, dict] = {}
        trajectories: dict[str, dict] = {}
        for key, tag in items.items():
            if tag.get("is_prompt", False):
                status = tag.get("status")
                if status not in {"pending", "running", *self.TERMINAL}:
                    raise ValueError(f"Unknown replay status {status!r} for {key!r}")
                if not isinstance(tag.get("global_steps"), int):
                    raise ValueError(f"Prompt {key!r} is missing integer global_steps")
                prompts[key] = dict(tag)
            else:
                trajectories[key] = dict(tag)
        return prompts, trajectories

    @staticmethod
    def _ordered_terminal_uids(prompts: dict[str, dict], global_steps: int) -> list[str]:
        terminal = [(uid, tag) for uid, tag in prompts.items() if tag["status"] in ReplayBuffer.TERMINAL]
        for uid, tag in terminal:
            if tag["global_steps"] > global_steps:
                raise ValueError(
                    f"Replay prompt {uid!r} was generated by future weight version "
                    f"{tag['global_steps']} > {global_steps}"
                )
        terminal.sort(key=lambda item: (item[1]["global_steps"], item[0]))
        return [uid for uid, _ in terminal]

    def sample(self, global_steps: int, partition_id: str, batch_size: int) -> tuple[KVBatchMeta, dict]:
        if batch_size <= 0:
            raise ValueError("batch_size must be positive")
        started = time.monotonic()
        while True:
            prompts, trajectories = self._snapshot(partition_id)
            selected = self._ordered_terminal_uids(prompts, global_steps)[:batch_size]
            if len(selected) == batch_size:
                break
            if self.timeout is not None and time.monotonic() - started >= self.timeout:
                raise TimeoutError(
                    f"ReplayBuffer timed out waiting for {batch_size} terminal groups; found {len(selected)}"
                )
            time.sleep(self.poll_interval)

        selected_set = set(selected)
        keys, tags = [], []
        for key, tag in trajectories.items():
            if key.split("_", 1)[0] in selected_set:
                keys.append(key)
                tags.append(tag)
        if not keys:
            raise RuntimeError("Selected terminal replay groups have no materializable trajectories")
        self.store.kv_clear(partition_id=partition_id, keys=selected)
        staleness = [global_steps - prompts[uid]["global_steps"] for uid in selected]
        metrics = {
            "training/off_policy/sampled_staleness/mean": sum(staleness) / len(staleness),
            "training/off_policy/sampled_staleness/max": max(staleness),
        }
        return KVBatchMeta(partition_id=partition_id, keys=keys, tags=tags), metrics


class ReplayBufferAsync(ReplayBuffer):
    """Async replay policy with bounded policy staleness."""

    def __init__(self, *args, max_off_policy_threshold: int | None = None, strategy: str = "drop", **kwargs):
        super().__init__(*args, **kwargs)
        if max_off_policy_threshold is not None and max_off_policy_threshold <= 0:
            raise ValueError("max_off_policy_threshold must be positive or None")
        if strategy not in {"drop", "wait"}:
            raise ValueError("strategy must be 'drop' or 'wait'")
        self.max_off_policy_threshold = max_off_policy_threshold
        self.strategy = strategy

    def sample(self, global_steps: int, partition_id: str, batch_size: int):
        prompts, _ = self._snapshot(partition_id)
        stale = [
            uid
            for uid, tag in prompts.items()
            if tag["status"] in self.TERMINAL
            and self.max_off_policy_threshold is not None
            and global_steps - tag["global_steps"] > self.max_off_policy_threshold
        ]
        if stale and self.strategy == "drop":
            self.store.kv_clear(partition_id=partition_id, keys=stale)
        elif stale and self.strategy == "wait":
            raise RuntimeError(f"Async replay contains stale terminal groups under wait policy: {stale[:5]}")
        meta, metrics = super().sample(global_steps, partition_id, batch_size)
        metrics["training/off_policy/evicted_samples"] = len(stale) if self.strategy == "drop" else 0
        return meta, metrics
